# Types of variable 

# Integer Variable
age = 25
print("the age is:",age)

# string variable
student = "yash"
print ("the name of student is:",student)

# float variable
Height = 4.5
print("the hieght is:",Height)

# Boolean variable
is_student = True
print("the boolean value:",is_student)

# List variable 
Marks = [10,20,30,40]
print("the marks are:",Marks)